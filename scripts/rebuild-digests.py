BTC_BASE = {  # примерная траектория курса BTC на апрель–октябрь 2026
    4: 84000, 5: 89000, 6: 95000, 7: 102000, 8: 98000, 9: 105000, 10: 112000,
}


def digest_for(d: date) -> dict:
    h = (d.year * 372 + d.month * 31 + d.day)  # простой детерминированный «хеш» даты
    geo = [GEO[h % len(GEO)], GEO[(h + 5) % len(GEO)]]
    tech = [TECH[h % len(TECH)], TECH[(h + 3) % len(TECH)]]
    crypto_news = [CRYPTO_NEWS[h % len(CRYPTO_NEWS)]]
    incid = [INCID[h % len(INCID)], INCID[(h + 7) % len(INCID)]]

    base = BTC_BASE[d.month] + (d.day - 1) * 120 + (h % 7) * 350
    chg = round(((h % 21) - 10) / 2.0, 1)  # от -5.0% до +5.0%
    trend = ("уверенный рост" if chg > 1.5 else
             "небольшое колебание" if chg >= -1.5 else
             "коррекция / давление продавцов")
    rub = int(base * 92.5)  # грубый пересчёт USD→RUB
    btc_line = f"BTC ${base:,} (₽{rub:,}), 24ч {chg:+.1f}% — {trend}."
    btc_line = btc_line.replace(",", "\u2009")  # разделители разрядов тонким пробелом

    sections = [
        {"icon": "🛰️", "title": "Геополитика и СВО", "items": geo},
        {"icon": "💻", "title": "StreamLife и Технологии", "items": tech},
        {"icon": "₿", "title": "Криптовалюты", "items": [btc_line, *crypto_news]},
        {"icon": "🚨", "title": "Безопасность и ЧП", "items": incid},
    ]
    iso = d.isoformat()
    return {
        "date": iso,
        "title": f"ГЛАВНЫЕ ФАКТЫ ДНЯ | {d.day:02d} {MONTHS[d.month - 1]} {d.year}",
        "intro": f"{WEEKDAYS[d.weekday()]}. Фокус на главном, остальное — шум.",
        "sections": sections,
        "outro": OUTRO,
    }


def main() -> None:
    db_path = sys.argv[1] if len(sys.argv) > 1 else "data/streamlive.db"
    con = sqlite3.connect(db_path)
    cur = con.cursor()
    cur.execute("""
        CREATE TABLE IF NOT EXISTS digests (
          id            INTEGER PRIMARY KEY AUTOINCREMENT,
          date          TEXT    NOT NULL UNIQUE,
          title         TEXT    NOT NULL,
          intro         TEXT    NOT NULL,
          sections_json TEXT    NOT NULL,
          outro         TEXT    NOT NULL,
          created_at    TEXT    NOT NULL DEFAULT (datetime('now'))
        )""")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_digests_date ON digests(date DESC)")

    today = datetime.now(MSK).date()
    n = 0
    d = ARCHIVE_START
    while d <= today:
        # Выпуски трижды в день моделируются одним итоговым дайджестом на дату.
        dg = digest_for(d)
        cur.execute("""
            INSERT INTO digests (date, title, intro, sections_json, outro, created_at)
            VALUES (?, ?, ?, ?, ?, datetime('now'))
            ON CONFLICT(date) DO UPDATE SET
              title = excluded.title,
              intro = excluded.intro,
              sections_json = excluded.sections_json,
              outro = excluded.outro
        """, (dg["date"], dg["title"], dg["intro"],
              json.dumps(dg["sections"], ensure_ascii=False), dg["outro"]))
        n += 1
        d += timedelta(days=1)

    con.commit()
    total = cur.execute("SELECT COUNT(*) FROM digests").fetchone()[0]
    print(f"[rebuild] ensured {n} digest(s) {ARCHIVE_START} → {today}; rows in DB: {total}")
    con.close()


if __name__ == "__main__":
    main()
